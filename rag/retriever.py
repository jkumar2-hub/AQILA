def index_audio_chunks(
    segments: list[dict[str, Any]],
    source_id: str,
    file_name: str,
) -> int:
    """
    Embed Whisper transcript segments and index them into audio_col.
    """

    from backend.app.db.chroma import audio_col

    if not segments:
        return 0

    valid_segments = [
        segment
        for segment in segments
        if segment.get("text", "").strip()
    ]

    if not valid_segments:
        return 0

    texts = [
        segment["text"].strip()
        for segment in valid_segments
    ]

    embeddings = embed_texts(texts)

    ids: list[str] = []
    documents: list[str] = []
    metadatas: list[dict[str, Any]] = []

    for index, (segment, embedding) in enumerate(
        zip(valid_segments, embeddings)
    ):
        chunk_id = f"{source_id}:{index}"

        ids.append(chunk_id)
        documents.append(segment["text"].strip())

        metadatas.append(
            {
                "source_id": source_id,
                "file_name": file_name,
                "modality": "audio",
                "chunk_index": index,
                "source_type": "audio",
                "timestamp_start": segment.get("timestamp_start"),
                "timestamp_end": segment.get("timestamp_end"),
            }
        )

    audio_col.upsert(
        ids=ids,
        documents=documents,
        embeddings=embeddings,
        metadatas=metadatas,
    )

    return len(ids)

