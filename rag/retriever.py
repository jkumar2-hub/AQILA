def retrieve_audio_p1(
    query: str,
    top_k: int = 4,
) -> list[RetrievalResult]:
    """
    Retrieve timestamped audio transcript chunks from audio_col.
    """

    from backend.app.db.chroma import audio_col

    if not query or not query.strip():
        return []

    if audio_col.count() == 0:
        return []

    query_embedding = embed_texts([query])[0]

    result = audio_col.query(
        query_embeddings=[query_embedding],
        n_results=min(top_k, audio_col.count()),
        include=[
            "documents",
            "metadatas",
            "distances",
            "embeddings",
        ],
    )

    documents = result.get("documents", [[]])[0]
    metadatas = result.get("metadatas", [[]])[0]
    distances = result.get("distances", [[]])[0]
    embeddings = result.get("embeddings", [[]])[0]

    retrieval_results: list[RetrievalResult] = []

    for index, text in enumerate(documents):
        metadata = metadatas[index] or {}

        distance = distances[index]

        score = max(
            0.0,
            min(
                1.0,
                1.0 - float(distance),
            ),
        )

        embedding = None

        if embeddings is not None and index < len(embeddings):
            embedding = list(embeddings[index])

        source_id = metadata["source_id"]
        chunk_index = metadata["chunk_index"]

        retrieval_results.append(
            RetrievalResult(
                query=query,
                source_id=source_id,
                source_type="audio",
                chunk_id=f"{source_id}:{chunk_index}",
                text=text,
                score=score,
                modality="audio",
                page_number=None,
                timestamp_start=metadata.get("timestamp_start"),
                timestamp_end=metadata.get("timestamp_end"),
                file_name=metadata["file_name"],
                file_created_at=None,
                metadata=metadata,
                embedding=embedding,
                embedding_space="minilm",
            )
        )

    return retrieval_results